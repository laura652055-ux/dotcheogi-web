const MOODS = { idle: IDLE, happy: HAPPY, sad: SAD, think: THINK }

/** 가로로 이어진 '#' 를 하나의 rect 로 합친다. 노드 수를 줄이려는 것. */
function toRects(rows) {
  const rects = []
  rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      if (row[x] !== '#') {
        x += 1
        continue
      }
      let end = x
      while (end + 1 < row.length && row[end + 1] === '#') end += 1
      rects.push({ x, y, w: end - x + 1 })
      x = end + 1
    }
  })
  return rects
}

const CACHE = Object.fromEntries(
  Object.entries(MOODS).map(([k, rows]) => [k, toRects(rows)]),
)

export default function Mascot({ mood = 'idle', size = 64, className, title }) {
  const rects = CACHE[mood] ?? CACHE.idle
  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox="0 0 16 16"
      shapeRendering="crispEdges"
      role={title ? 'img' : 'presentation'}
      aria-label={title}
      aria-hidden={title ? undefined : true}
      style={{ flex: 'none', display: 'block' }}
    >
      {rects.map((r) => (
        <rect
          key={`${r.x}-${r.y}`}
          x={r.x}
          y={r.y}
          width={r.w}
          height={1}
          fill="var(--ink)"
        />
      ))}
    </svg>
  )
}

